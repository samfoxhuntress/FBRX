#!/usr/bin/env node
/**
 * Builds FBRX's own knowledge for the agent from the guides (README.md and docs/*.md): one entry per section, written
 * to packages/core/src/knowledge/docs.generated.ts. FBRX loads it into a local search database on each computer, so
 * the agent can answer questions about FBRX (and fix it) without going online.
 *
 *   node scripts/build-knowledge.mjs          write it
 *   node scripts/build-knowledge.mjs --check  fail when it is out of date (a test runs this)
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'packages/core/src/knowledge/docs.generated.ts');
const MAX = 5000;

export function sections() {
  const files = ['README.md', ...readdirSync(join(ROOT, 'docs')).filter((f) => f.endsWith('.md')).sort().map((f) => `docs/${f}`)];
  const out = [];
  for (const file of files) {
    const text = readFileSync(join(ROOT, file), 'utf8')
      .replace(/<[^>]+>/g, '')
      .replace(/\r\n/g, '\n');
    let docTitle = file;
    let heading = [];
    let body = [];
    let fence = false;
    const flush = () => {
      const t = body.join('\n').replace(/\n{3,}/g, '\n\n').trim();
      if (t.length > 40) {
        const title = [docTitle, ...heading].filter(Boolean).join(' › ');
        for (let i = 0, part = 0; i < t.length; i += MAX, part++) out.push({ d: file, t: part ? `${title} (${part + 1})` : title, x: t.slice(i, i + MAX) });
      }
      body = [];
    };
    for (const line of text.split('\n')) {
      if (line.startsWith('```')) fence = !fence;
      const m = !fence && /^(#{1,3})\s+(.*)$/.exec(line);
      if (m) {
        flush();
        const level = m[1].length;
        const h = m[2].replace(/[*_`]/g, '').trim();
        if (level === 1) {
          docTitle = h;
          heading = [];
        } else heading = level === 2 ? [h] : [heading[0] ?? '', h].filter(Boolean);
        continue;
      }
      body.push(line);
    }
    flush();
  }
  return out;
}

const render = (s) =>
  `// Generated by scripts/build-knowledge.mjs from README.md and docs/*.md. Do not edit; run npm run knowledge.\n` +
  `/** FBRX's guides, one entry per section: d = file, t = section title, x = text. */\n` +
  `export const DOC_SECTIONS: ReadonlyArray<{ d: string; t: string; x: string }> = ${JSON.stringify(s, null, 0)};\n`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = render(sections());
  if (process.argv.includes('--check')) {
    // A Windows checkout may have turned the file's line endings into CRLF.
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== next) {
      console.error('packages/core/src/knowledge/docs.generated.ts is out of date: run npm run knowledge');
      process.exit(1);
    }
    console.log('FBRX knowledge is up to date');
  } else {
    writeFileSync(OUT, next);
    console.log(`Wrote ${sections().length} sections to ${OUT}`);
  }
}
